const dictionaries: Record<Locale, Record<string, string>> = { en, 'zh-CN': zhCN, ja, ko };

function normalizeLocale(value?: string | null): Locale {
  const normalized = value?.toLowerCase();
  if (normalized?.startsWith('zh')) return 'zh-CN';
  if (normalized?.startsWith('ja')) return 'ja';
  if (normalized?.startsWith('ko')) return 'ko';
  return 'en';
}

function initialLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved) return normalizeLocale(saved);
  } catch {
    // Some WebView origins can temporarily deny storage during startup.
  }
  return normalizeLocale(window.navigator.languages?.[0] ?? window.navigator.language);
}

const localeStore = writable<Locale>(initialLocale());

function applyLocale(value: Locale) {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(STORAGE_KEY, value);
  } catch {
    // Language switching still works for the current session.
  }
  document.documentElement.lang = value;
}

export const locale = {
  subscribe: localeStore.subscribe,
  set(value: Locale) {
    localeStore.set(value);
    applyLocale(value);
  }
};

export const t = derived(localeStore, ($locale): Translate => (key, params = {}) => {
  let value = dictionaries[$locale][key] ?? en[key] ?? key;
  for (const [name, replacement] of Object.entries(params)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
});

